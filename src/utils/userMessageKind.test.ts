import { describe, expect, it } from "vitest";
import type { ClaudeMessage } from "@/types";
import {
  getPromptPreview,
  getUserMessageKind,
  getUserMessageText,
  isHumanPrompt,
} from "./userMessageKind";

const user = (content: unknown): ClaudeMessage =>
  ({
    uuid: "u1",
    sessionId: "s1",
    timestamp: "2026-09-24T10:00:00.000Z",
    type: "user",
    role: "user",
    content,
  }) as ClaudeMessage;

const assistant = (): ClaudeMessage =>
  ({
    uuid: "a1",
    sessionId: "s1",
    timestamp: "2026-09-24T10:00:01.000Z",
    type: "assistant",
    role: "assistant",
    content: [{ type: "text", text: "Done." }],
  }) as ClaudeMessage;

describe("getUserMessageKind", () => {
  it.each([
    ["plain prompt", "Why does the build fail?", "prompt"],
    ["prompt with leading whitespace", "\n  fix the header", "prompt"],
    ["slash command", "<command-message>model</command-message>\n<command-name>/model</command-name>", "command"],
    ["slash command name first", "<command-name>/init</command-name>", "command"],
    ["bash mode input", "<bash-input>ls</bash-input>", "command"],
    ["command stdout", "<local-command-stdout>Set model to Opus</local-command-stdout>", "commandOutput"],
    ["command caveat", "<local-command-caveat>Caveat: generated by local commands</local-command-caveat>", "commandOutput"],
    ["bash mode output", "<bash-stdout>file.txt</bash-stdout>", "commandOutput"],
    ["task notification", "<task-notification>\n<task-id>b1</task-id>\n</task-notification>", "taskNotification"],
    ["system reminder", "<system-reminder>Context</system-reminder>", "systemContext"],
    ["codex AGENTS.md block", "# AGENTS.md instructions for /repo\n<INSTRUCTIONS>", "systemContext"],
    ["codex environment context", "<environment_context>\n<cwd>/repo</cwd>", "systemContext"],
    ["interrupt", "[Request interrupted by user]", "interrupt"],
    ["interrupt for tool use", "[Request interrupted by user for tool use]", "interrupt"],
    ["compact summary", "This session is being continued from a previous conversation that ran out of context.", "compactSummary"],
    ["empty string", "   ", "empty"],
  ])("%s", (_label, content, expected) => {
    expect(getUserMessageKind(user(content))).toBe(expected);
  });

  it("treats a tool_result array as a tool result", () => {
    const message = user([{ type: "tool_result", tool_use_id: "t1", content: "ok" }]);
    expect(getUserMessageKind(message)).toBe("toolResult");
  });

  it("reads text blocks of array content", () => {
    const message = user([{ type: "text", text: "Refactor the parser" }]);
    expect(getUserMessageKind(message)).toBe("prompt");
    expect(getUserMessageText(message)).toBe("Refactor the parser");
  });

  it("classifies tag-prefixed text blocks by their text", () => {
    const message = user([{ type: "text", text: "<task-notification>x</task-notification>" }]);
    expect(getUserMessageKind(message)).toBe("taskNotification");
  });

  it("counts an image-only message as a prompt", () => {
    const message = user([{ type: "image", source: { type: "base64", data: "", media_type: "image/png" } }]);
    expect(getUserMessageKind(message)).toBe("prompt");
  });

  it("does not match tags that appear later in a prompt", () => {
    expect(getUserMessageKind(user("Explain what <task-notification> means"))).toBe("prompt");
  });

  it("returns null for non-user records", () => {
    expect(getUserMessageKind(assistant())).toBeNull();
    expect(isHumanPrompt(assistant())).toBe(false);
  });
});

describe("getPromptPreview", () => {
  it("uses the first line of a short prompt", () => {
    expect(getPromptPreview("Fix the login bug\nIt happens on Safari")).toEqual({
      text: "Fix the login bug",
      fromTail: false,
    });
  });

  it("uses the closing question after pasted context", () => {
    const pasted = Array.from({ length: 40 }, (_, i) => `at frame ${i} (app.js:${i})`).join("\n");
    const preview = getPromptPreview(`${pasted}\n\nWhy does this fail on startup?`);
    expect(preview).toEqual({ text: "Why does this fail on startup?", fromTail: true });
  });

  it("keeps the first line when the closing paragraph is long", () => {
    const text = `Intro line\n\n${"word ".repeat(120)}`;
    expect(getPromptPreview(text).fromTail).toBe(false);
    expect(getPromptPreview(text).text).toBe("Intro line");
  });

  it("does not pick a trailing code block as the question", () => {
    const text = `${"context ".repeat(80)}\n\n\`\`\`ts\nconst x = 1;\n\`\`\``;
    expect(getPromptPreview(text).fromTail).toBe(false);
  });

  it("collapses whitespace and truncates", () => {
    const preview = getPromptPreview(`   ${"a ".repeat(200)}`, 20);
    expect(preview.text.length).toBeLessThanOrEqual(20);
    expect(preview.text.endsWith("…")).toBe(true);
  });

  it("returns an empty preview for empty text", () => {
    expect(getPromptPreview("  \n ")).toEqual({ text: "", fromTail: false });
  });
});
